"""
predict_samples.py
اجرای مدل روی چند عکس نمونه و ذخیره‌ی عکس‌های خروجی با باکس دور عیب‌ها
(این عکس‌ها مستقیم توی README و رزومه/ارائه استفاده میشن)
"""

from ultralytics import YOLO
import os

# ---------- تنظیمات ----------
MODEL_PATH = "best.pt"                          # مسیر وزن مدل آموزش‌دیده (baseline)
SOURCE_DIR = "sample_images"                    # پوشه‌ی عکس‌های نمونه (چندتا از val/Roboflow بریز اینجا)
OUTPUT_DIR = "predictions_for_readme"           # پوشه‌ی خروجی که عکس‌های نهایی توش ذخیره میشن
CONF_THRESHOLD = 0.35                           # حداقل اطمینان برای نمایش یک باکس (پایین‌تر = حساس‌تر)

# ---------- بارگذاری مدل ----------
model = YOLO(MODEL_PATH)                        # بارگذاری وزن‌های آموزش‌دیده

# ---------- اجرای پیش‌بینی روی همه‌ی عکس‌های پوشه ----------
results = model.predict(
    source=SOURCE_DIR,
    conf=CONF_THRESHOLD,
    save=True,                                  # ultralytics خودش عکس با باکس رسم‌شده رو ذخیره می‌کنه
    project=OUTPUT_DIR,
    name="samples",
    exist_ok=True,
)

print(f"✅ عکس‌های نمونه ذخیره شدن توی: {OUTPUT_DIR}/samples/")
print("این پوشه رو مستقیم توی ریپوی گیت‌هاب (پوشه‌ی assets/) و README استفاده کن.")

# ---------- (اختیاری) چاپ خلاصه‌ی تشخیص هر عکس ----------
for r in results:
    filename = os.path.basename(r.path)
    num_detections = len(r.boxes)
    print(f"{filename}: {num_detections} عیب پیدا شد")


